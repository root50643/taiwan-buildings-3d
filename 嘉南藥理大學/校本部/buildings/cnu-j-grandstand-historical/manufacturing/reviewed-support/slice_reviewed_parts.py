"""Reproduce the conditionally reviewed diagnostic route, never machine code.

Set PRUSA_SLICER to PrusaSlicer 2.9.6 and PRIVATE_SLICE_DIR outside the package.
Default: only main_body, because the other profiles and geometry are unchanged.
Use --all to slice four unique geometries (1+1+10+10 remains 22 physical pieces).
Optionally set REFERENCE_REVIEW_GCODE to the independent short-axis diagnostic
to verify every G-code line except its generated-time comment.
"""
from pathlib import Path
import os,sys,json,hashlib,re,subprocess,importlib.util
sys.dont_write_bytecode=True
HERE=Path(__file__).resolve().parent;ROOT=HERE.parents[1]
SUPPORT=ROOT/'qa/independent-support-review/slicing-support-audit'

def sha(p):return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def canonical(b):
    # Only this comment is time dependent. Do not remove other commands/comments.
    return b''.join(line for line in b.splitlines(keepends=True)
                    if not line.startswith(b'; generated by PrusaSlicer '))

def main():
    exe=Path(os.environ['PRUSA_SLICER']).resolve(strict=True)
    private=Path(os.environ['PRIVATE_SLICE_DIR']).resolve()
    if private==ROOT or ROOT in private.parents:raise RuntimeError('Diagnostic G-code must remain outside the delivered model package')
    private.mkdir(parents=True,exist_ok=True)
    spec=importlib.util.spec_from_file_location('independent_modal_parser',SUPPORT/'modal_capsule_helpers.py')
    m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)
    names=['main_body','roof','column','mast_brace_frame'] if '--all' in sys.argv else ['main_body']
    report={'decision':'CONDITIONAL_GO_FIXED_STLS_ONLY','old_main_route_accepted':False,
            'machine_ready':False,'physical_print_or_fit_or_glue_test':False,
            'conditions':'100% size; PLA; 0.4mm nozzle; 0.2mm layer; nominal 0.45mm width; 3 perimeters; 15% stars infill; 250x210mm bed; no brim in this diagnostic.',
            'results':[]}
    for name in names:
        profile=HERE/'main-short-axis-support.ini' if name=='main_body' else ROOT/'qa/manufacturing-review/diagnostic-no-support.ini'
        out=private/(name+'-REVIEWED-DIAGNOSTIC-DO-NOT-PRINT.gcode')
        datadir=private/(name+'-isolated-settings');datadir.mkdir(exist_ok=True)
        stl=ROOT/'parts'/(name+'-print.stl')
        args=[str(exe),'--datadir',str(datadir),'--load',str(profile),'--center','125,105','--export-gcode','--output',str(out),str(stl)]
        run=subprocess.run(args,cwd=ROOT,capture_output=True,text=True,encoding='utf-8',errors='replace')
        clean=(run.stdout+'\n'+run.stderr).replace(str(ROOT),'${MODEL_PACKAGE}').replace(str(private),'${PRIVATE_SLICE_DIR}').replace(str(exe.parent),'${SLICER_DIR}')
        (HERE/(name+'-integration-reslice.log')).write_text(clean,encoding='utf-8')
        warnings=[line for line in clean.splitlines() if re.search(r'warning|error|repair',line,re.I)]
        if run.returncode or not out.exists():raise RuntimeError(clean)
        parsed=m.parse_gcode(out)
        segs=parsed['_segments']
        support=[s for s in segs if s['type'].startswith('Support')]
        bridges=[s for s in segs if s['type']=='Bridge infill']
        item={'part':name,'input_sha256':sha(stl),'profile':profile.relative_to(ROOT).as_posix(),
              'profile_sha256':sha(profile),'exit_code':run.returncode,'warning_lines':warnings,
              'gcode_sha256':sha(out),'gcode_bytes':out.stat().st_size,
              'gcode_canonical_sha256':hashlib.sha256(canonical(out.read_bytes())).hexdigest(),
              'support_extrusion_segments':len(support),'bridge_extrusion_segments':len(bridges),
              'command_template':['${PRUSA_SLICER}','--datadir','${PRIVATE_SLICE_DIR}/'+datadir.name,'--load',profile.relative_to(ROOT).as_posix(),'--center','125,105','--export-gcode','--output','${PRIVATE_SLICE_DIR}/'+out.name,'parts/'+stl.name],
              'raw_gcode_in_package':False}
        ref=os.environ.get('REFERENCE_REVIEW_GCODE') if name=='main_body' else None
        if ref:
            rb=Path(ref).read_bytes();item['reference_review_gcode_sha256']=hashlib.sha256(rb).hexdigest()
            item['identical_to_independent_review_except_generated_time']=canonical(out.read_bytes())==canonical(rb)
            if not item['identical_to_independent_review_except_generated_time']:raise RuntimeError('Reference toolpath differs; do not inherit its bridge/support measurements')
        report['results'].append(item)
    report['limitations']=[
        'Check actual bridge direction across the short platform span, not angle number alone; rotation/slicer changes affect meaning.',
        'Retain support under bridges. The main platform centerline coverage gap is about 1.704001mm only under the linked independent toolpath analysis.',
        'About 8.224913mm main / 8.036027mm roof internal bridges still require demonstrated machine/material capability or a revised reslice.',
        '95,890 support points and staged routes are finite geometric checks, not a full removal, tool-turning, adhesion or strength simulation.',
        'Break support into small pieces and remove laterally before assembly; do not pull the two shallow-window support blocks straight forward.',
        'Fit and adhesive strength are untested; 50 joints are glue alignment, not snap fits.']
    (HERE/'integration-reslice.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(report,indent=2))

if __name__=='__main__':main()
