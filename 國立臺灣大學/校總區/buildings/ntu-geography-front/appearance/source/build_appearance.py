A=Path(__file__).resolve().parents[1];R=A.parent
SOURCE_SHA='91b02a6dd3a1d3d889ec0d2497f36ebde39437bbd1d04609aead9771f0fbc4ad'
PALETTE=[('neutral_unknown','#AAA79F'),('pale_cream_tiled_wall','#C6C3AC'),('muted_bluegray_window_strip','#85949C'),('dark_gray_mullions','#707B7B'),('gray_concrete_portico','#9FA39D')]
def classify(tri):
 t=tri;lo=t.min(axis=1);hi=t.max(axis=1)
 color=np.zeros(len(t),dtype=int);why=np.full(len(t),'unregistered_sides_rear_roof_groundfloor_mixed_recess_neutral',dtype=object)
 def paint(m,k,r):color[m]=k;why[m]=r
 def zz(a,b):return (lo[:,2]>=a-.003)&(hi[:,2]<=b+.003)
 def xx(a,b):return (lo[:,0]>=a-.003)&(hi[:,0]<=b+.003)
 def yy(a,b):return (lo[:,1]>=a-.003)&(hi[:,1]<=b+.003)
 def plane(i,v):return np.all(abs(t[:,:,i]-v)<.004,axis=1)
 def box(a,b,c,d,e,f):return xx(a,b)&yy(c,d)&zz(e,f)
 paint(plane(1,-14)&xx(-67,67)&zz(2.8,115.8),1,'source_front_pale_cream_solid_tiled_wall')
 for z in [27,46,65,84,103]:
  paint(plane(1,-12.5)&xx(-63.5,63.5)&zz(z,z+9),2,'source_continuous_upper_glazed_strip_back_only')
  for x in range(-60,61,8):paint(box(x-.5,x+.5,-14.6,-12.6,z,z+9),3,'source_existing_gray_vertical_window_mullions')
  paint(box(-65,65,-16.5,-13.5,z-1.3,z),1,'source_existing_cream_window_sill_band')
 paint(box(-33,63,-44,-12,21,25),4,'source_gray_portico_cap_bounded_same_material_top')
