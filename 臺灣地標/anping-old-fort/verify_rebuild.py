"""Rebuild byte-for-byte; verify raw STL normals and closed shell inventory."""
import hashlib,json,subprocess,sys,tempfile
from pathlib import Path
import numpy as np
import trimesh
P=Path(__file__).resolve().parent
sha=lambda p:hashlib.sha256(Path(p).read_bytes()).hexdigest()
with tempfile.TemporaryDirectory() as td:
    dst=Path(td)/'rebuilt.stl'
    subprocess.run([sys.executable,str(P/'build_model.py'),'--output',str(dst)],check=True,capture_output=True)
    rebuilt=sha(dst)
mesh=trimesh.load(P/'model.stl',force='mesh',process=True)
raw=(P/'model.stl').read_bytes();num=int.from_bytes(raw[80:84],'little')
dtype=np.dtype([('normal','<f4',(3,)),('vertices','<f4',(3,3)),('attr','<u2')]);data=np.frombuffer(raw,dtype=dtype,count=num,offset=84)
actual=np.cross(data['vertices'][:,1]-data['vertices'][:,0],data['vertices'][:,2]-data['vertices'][:,0]);actual/=np.linalg.norm(actual,axis=1)[:,None]
normal_ok=bool(np.all(np.sum(actual*data['normal'],axis=1)>.9999))
shells=mesh.split(only_watertight=False)
# Sample each nominal 0.2-mm layer through the full object.
zvals=np.arange(.1,mesh.bounds[1,2],.2);empty=[]
for z in zvals:
    section=trimesh.intersections.mesh_plane(mesh,[0,0,1],[0,0,z])
    if not len(section):empty.append(float(z))
checks={'source_rebuild_identical_sha256':sha(P/'model.stl')==rebuilt,'raw_stl_normals_match_triangle_winding':normal_ok,'exactly_one_closed_boundary':len(shells)==1 and bool(shells[0].is_watertight),'no_negative_volume_inner_shells':all(c.volume>0 for c in shells),'no_empty_sampled_layers':not empty}
report={'passed':all(checks.values()),'checks':checks,'original_stl_sha256':sha(P/'model.stl'),'rebuilt_stl_sha256':rebuilt,'closed_boundary_count':len(shells),'boundary_signed_volumes_mm3':[float(c.volume) for c in shells],'euler_characteristic':int(mesh.euler_number),'sample_interval_mm':.2,'sampled_layers':len(zvals),'empty_layers_mm':empty,'limitations':['One closed connected boundary and positive signed shell volume show no isolated inner cavity shell. Open exterior step grooves may create topological handles.','This is a topology, raw-normal, reproducibility and section-continuity test, not a physical print or support test.','The STL was generated by Manifold solid booleans; this test is not an independent exhaustive triangle self-intersection proof.']}
(P/'rebuild_validation.json').write_text(json.dumps(report,indent=2,ensure_ascii=False));print(json.dumps(report,indent=2));assert report['passed']
