"""Independent read-only slice audit. Never sends G-code to a machine."""
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor
import hashlib,json,re,subprocess,math,sys
from collections import defaultdict,Counter
import numpy as np

ROOT=Path(__file__).resolve().parent
PACKAGE=ROOT.parent/'candidate'
ORIGINAL=Path('${ORIGINAL_DIAGNOSTIC_GCODE_DIR}')
SLICER=Path('${PRUSASLICER_2_9_6_DIR}/prusa-slicer-console.exe')
PARTS=['main_body','roof','column','mast_brace_frame']
QUANTITY=[1,1,10,10]
PARAM=re.compile(r'([A-Za-z])\s*([-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?)')
def sha(p): return hashlib.sha256(p.read_bytes()).hexdigest()
def parse(p,save_segments=False):
    xyz=np.zeros(3);e=0.;abs_xyz=True;abs_e=True;unit=1.;role='unspecified';layers=0
    roles={};segments=[];modes=[];unsupported=[];commands=Counter();object_z=set();settings={};times=[]
    for ln,line in enumerate(p.read_text(encoding='utf8').splitlines(),1):
        if line.startswith(';TYPE:'):role=line[6:].strip()
        if line.startswith(';LAYER_CHANGE'):layers+=1
        if line.startswith('; estimated printing time'):times.append(line.lstrip('; '))
        if line.startswith('; ') and ' = ' in line:
            k,v=line[2:].split(' = ',1);settings[k]=v
        code=line.split(';',1)[0].strip()
        if not code:continue
        cmd=code.split()[0].upper();commands[cmd]+=1
        vals={k.upper():float(v) for k,v in PARAM.findall(code[len(cmd):])}
        if cmd in ('G90','G91','M82','M83','G20','G21'):
            modes.append([ln,cmd])
            if cmd=='G90':abs_xyz=True
            elif cmd=='G91':abs_xyz=False
            elif cmd=='M82':abs_e=True
            elif cmd=='M83':abs_e=False
            elif cmd=='G20':unit=25.4
            elif cmd=='G21':unit=1.
            continue
        if cmd=='G92':
            for i,k in enumerate('XYZ'):
                if k in vals:xyz[i]=vals[k]*unit
            if 'E' in vals:e=vals['E']*unit
            continue
        if cmd in ('G2','G3','G5'):unsupported.append([ln,cmd]);continue
        if cmd not in ('G0','G1'):continue
        new=xyz.copy()
        for i,k in enumerate('XYZ'):
            if k in vals:new[i]=(vals[k]*unit) if abs_xyz else xyz[i]+vals[k]*unit
        en=(vals['E']*unit if abs_e else e+vals['E']*unit) if 'E' in vals else e
        de=en-e;dist=float(np.linalg.norm(new[:2]-xyz[:2]))
        if de>1e-8 and dist>1e-8:
            if not role.startswith('Support') and role not in ('Skirt/Brim','unspecified'):object_z.add(round(float(new[2]),5))
            r=roles.setdefault(role,{'count':0,'filament_mm':0.,'xy_length_mm':0.,'min_xyz':[float('inf')]*3,'max_xyz':[-float('inf')]*3,'z':set()})
            r['count']+=1;r['filament_mm']+=de;r['xy_length_mm']+=dist
            r['min_xyz']=np.minimum(r['min_xyz'],np.minimum(xyz,new)).tolist()
            r['max_xyz']=np.maximum(r['max_xyz'],np.maximum(xyz,new)).tolist();r['z'].add(round(float(new[2]),5))
            segments.append((xyz.copy(),new.copy(),role,ln,de))
        xyz=new;e=en
    for v in roles.values():v['z']=sorted(v['z'])
    out={'sha256':sha(p),'bytes':p.stat().st_size,'mode_commands':modes,'command_counts':dict(commands),'unparsed_motion_commands':unsupported,'layer_change_records':layers,'object_z_count':len(object_z),'object_z_mm':sorted(object_z),'roles':roles,'settings':settings,'time_comments':times}
    return (out,segments) if save_segments else out

def normalization(p):
    return re.sub(r'^; generated by PrusaSlicer[^\r\n]*', '; generated by PrusaSlicer TIMESTAMP REMOVED',p.read_text(encoding='utf8'),flags=re.M)

def main():
    ROOT.mkdir(parents=True,exist_ok=True); (ROOT/'raw-reslice-private').mkdir(exist_ok=True)
    ver=subprocess.run([str(SLICER),'--version'],capture_output=True,text=True)
    (ROOT/'slicer-version.txt').write_text(ver.stdout+ver.stderr,encoding='utf8')
    author=json.loads((PACKAGE/'qa/manufacturing-review/slicing-summary.json').read_text(encoding='utf8'))
    def run(item):
        n,q=item; profile=PACKAGE/'qa/manufacturing-review'/('diagnostic-main-support.ini' if n=='main_body' else 'diagnostic-no-support.ini')
        out=ROOT/'raw-reslice-private'/(n+'-DO-NOT-PRINT.gcode');datadir=ROOT/'raw-reslice-private'/(n+'-isolated-settings');datadir.mkdir(exist_ok=True)
        cmd=[str(SLICER),'--datadir',str(datadir),'--load',str(profile),'--center','125,105','--export-gcode','--output',str(out),str(PACKAGE/'parts'/(n+'-print.stl'))]
        r=subprocess.run(cmd,capture_output=True,text=True,encoding='utf8',errors='replace')
        (ROOT/(n+'-independent-slice.log')).write_text(r.stdout+r.stderr,encoding='utf8')
        original=ORIGINAL/(n+'-DIAGNOSTIC-ONLY.gcode');src,segments=parse(original,True);new=parse(out)
        expected=next(x for x in author['results'] if x['part']==n)
        result={'part':n,'quantity_required':q,'input_stl_sha256':sha(PACKAGE/'parts'/(n+'-print.stl')),'profile_sha256':sha(profile),'command':cmd,'exit_code':r.returncode,'warning_error_repair_lines':[l for l in (r.stdout+r.stderr).splitlines() if re.search('warn|error|repair',l,re.I)],'author_gcode_hash_matches':sha(original)==expected['gcode_sha256'],'author_input_hash_matches':sha(PACKAGE/'parts'/(n+'-print.stl'))==expected['input_sha256'],'original':src,'independent_reslice':new,'byte_identical_after_generated_timestamp_removed':normalization(original)==normalization(out)}
        # Compact immutable path array for further geometry and bridge analysis.
        keep=[s for s in segments if s[2].startswith('Support') or s[2]=='Bridge infill']
        np.savez_compressed(ROOT/(n+'-selected-paths.npz'),a=np.array([x[0] for x in keep]),b=np.array([x[1] for x in keep]),role=np.array([x[2] for x in keep]),line=np.array([x[3] for x in keep]))
        return result
    with ThreadPoolExecutor(max_workers=4) as pool:results=list(pool.map(run,zip(PARTS,QUANTITY)))
    result={'scope':'Four unique files each independently sliced once. Twenty-two physical copies are not twenty-two independent slicing jobs. No machine execution, physical print, dry fit, support removal or adhesive strength test.','results':results}
    (ROOT/'slice-audit.json').write_text(json.dumps(result,indent=2)+'\n',encoding='utf8')
    print(json.dumps([{k:x[k] for k in ('part','quantity_required','exit_code','author_gcode_hash_matches','author_input_hash_matches','byte_identical_after_generated_timestamp_removed','warning_error_repair_lines')} for x in results],indent=2))
if __name__=='__main__':main()
