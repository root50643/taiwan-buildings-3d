"""Read-only incremental identity/profile/toolpath/archive audit; no slicing."""
from pathlib import Path
import datetime
import hashlib
import json
import re
import zipfile

ROOT = Path(__file__).resolve().parent
OLD = ROOT.parent / 'cnu-j-independent-review'
PACKAGE = ROOT / 'candidate'


def sha(data):
    return hashlib.sha256(data).hexdigest()


def save(name, obj):
    (ROOT / name).write_text(json.dumps(obj, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def config(path):
    result = {}
    for line in path.read_text(encoding='utf-8-sig').splitlines():
        if not line.strip() or line.lstrip().startswith(('#', ';', '[')) or '=' not in line:
            continue
        key, value = line.split('=', 1)
        assert key.strip() not in result, ('duplicate setting', key)
        result[key.strip()] = value.strip()
    return result


def check_manifest(text, lookup):
    results = []
    for line in text.splitlines():
        if not line.strip():
            continue
        match = re.fullmatch(r'([a-fA-F0-9]{64})\s+\*?(.+)', line)
        assert match, ('Unrecognized manifest line', line)
        expected, rel = match.groups()
        actual = sha(lookup(rel))
        assert actual == expected.lower(), rel
        results.append({'path': rel, 'sha256': actual})
    return results


def main():
    receipt = json.loads((ROOT / 'author-delivery.json').read_text(encoding='utf-8-sig'))
    provenance = json.loads((ROOT / 'provenance.json').read_text(encoding='utf-8'))
    assert provenance['fixed_commit'] == '7cf0563a06858137f51751600348a35198c8f6f2'
    assert provenance['base_commit'] == '1976d60d5e1621dac2ce6a5d904e74796c38be0e'
    # All original files must still exist; only the six documented texts/seals differ.
    modified = [x['path'] for x in provenance['delta_from_58_file_snapshot'] if x['status'] == 'modified']
    expected_modified = ['MANIFEST.sha256', 'README.md', 'freeze-record.json', 'qa-summary.json', 'qa/manufacturing-review/README.md', 'qa/repository-scope.json']
    assert sorted(modified) == sorted(expected_modified)
    assert not provenance['removed_old_files']
    unchanged_rows = []
    for path in sorted((OLD / 'candidate').rglob('*')):
        if not path.is_file():
            continue
        rel = path.relative_to(OLD / 'candidate').as_posix()
        if rel in expected_modified:
            continue
        a, b = path.read_bytes(), (PACKAGE / rel).read_bytes()
        assert a == b, rel
        unchanged_rows.append({'path': rel, 'bytes': len(a), 'sha256': sha(a)})
    assert len(unchanged_rows) == 52
    print_stls = [r for r in unchanged_rows if r['path'].endswith('-print.stl')]
    assert len(print_stls) == 4
    original_profile = OLD / 'candidate/qa/manufacturing-review/diagnostic-main-support.ini'
    reviewed_profile = PACKAGE / 'manufacturing/reviewed-support/main-short-axis-support.ini'
    previous_review_profile = OLD / 'slicing-support-audit/REVIEW-ONLY-main-short-axis-support.ini'
    assert reviewed_profile.read_bytes() == previous_review_profile.read_bytes()
    a, b = config(original_profile), config(reviewed_profile)
    assert set(a) == set(b)
    changes = {k: {'old': a[k], 'new': b[k]} for k in a if a[k] != b[k]}
    assert changes == {'bridge_angle': {'old': '0', 'new': '90'}, 'dont_support_bridges': {'old': '1', 'new': '0'}}
    assert b['support_material'] == '1' and b['fill_density'] == '15%' and b['fill_pattern'] == 'stars'
    assert b['layer_height'] == '0.2' and b['nozzle_diameter'] == '0.4' and b['brim_width'] == '0'
    task = Path(receipt['local_checkout']).parent
    integrated_path = task / 'support-revision-private/main_body-REVIEWED-DIAGNOSTIC-DO-NOT-PRINT.gcode'
    reference_path = OLD / 'slicing-support-audit/raw-reslice-private/REVIEW-ONLY-main-short-axis-DO-NOT-PRINT.gcode'
    integrated, reference = integrated_path.read_bytes(), reference_path.read_bytes()
    ilines, rlines = integrated.splitlines(keepends=True), reference.splitlines(keepends=True)
    assert len(ilines) == len(rlines)
    differences = [i for i, pair in enumerate(zip(ilines, rlines)) if pair[0] != pair[1]]
    assert differences == [0]
    pattern = rb'; generated by PrusaSlicer 2\.9\.6 on \d{4}-\d{2}-\d{2} at \d{2}:\d{2}:\d{2} UTC\r?\n'
    assert re.fullmatch(pattern, ilines[0]) and re.fullmatch(pattern, rlines[0])
    assert sum(x.startswith(b'; generated by PrusaSlicer ') for x in ilines) == 1
    assert sum(x.startswith(b'; generated by PrusaSlicer ') for x in rlines) == 1
    assert ilines[1:] == rlines[1:]  # No other command, comment or line ending ignored.
    record = json.loads((PACKAGE / 'manufacturing/reviewed-support/integration-reslice.json').read_text(encoding='utf-8'))['results'][0]
    assert sha(integrated) == record['gcode_sha256'] == '896a8e3dcd229b515025ccb4c110344c725c7f67e82a1dc20ab0e2fc28974c98'
    canonical_sha = sha(b''.join(ilines[1:]))
    assert canonical_sha == record['gcode_canonical_sha256'] == 'dec08162c81c48cde9081124088a249a34de8133ecaf89e3b1a48baeb23ab053'
    assert sha(reviewed_profile.read_bytes()) == record['profile_sha256']
    identity = {
        'scope': 'Actual supplied diagnostic G-code read and byte-compared; no fresh slicing or machine execution. Only one generated-time comment at first line may differ.',
        'fixed_commit': provenance['fixed_commit'], 'unchanged_original_files': unchanged_rows,
        'unchanged_original_file_count': 52, 'changed_original_text_or_seal_files': modified,
        'added_package_files': 87, 'removed_original_files': [], 'fixed_print_stls': print_stls,
        'reviewed_profile_sha256': sha(reviewed_profile.read_bytes()),
        'profile_byte_identical_to_previous_independent_correction': True,
        'actual_setting_changes_from_original': changes,
        'actual_gcode': {'source': str(integrated_path), 'bytes': len(integrated), 'sha256': sha(integrated),
                        'previous_independent_reference_sha256': sha(reference), 'line_count': len(ilines),
                        'differing_lines_1based': [1], 'new_first_line': ilines[0].decode().rstrip(),
                        'reference_first_line': rlines[0].decode().rstrip(),
                        'all_remaining_bytes_identical': True, 'canonical_sha256': canonical_sha},
        'inherited_numeric_toolpath_findings_not_recomputed': {
            'main_platform_max_gap_mm': 1.704001, 'main_internal_max_gap_mm': 8.224913,
            'roof_internal_max_gap_mm': 8.036027, 'main_support_segments': 30369,
            'main_bridge_segments': 8132, 'main_support_sample_points': 95890, 'restricted_points': 580},
        'basis_for_inheritance': 'Identical STL, exact profile bytes and all G-code bytes other than the single generation-time comment.'
    }
    save('identity-profile-gcode.json', identity)
    package_checks = check_manifest((PACKAGE / 'MANIFEST.sha256').read_text(encoding='utf-8-sig'), lambda rel: (PACKAGE / rel).read_bytes())
    assert len(package_checks) == 144
    archive = Path(receipt['archive_local_path'])
    archive_sha = sha(archive.read_bytes())
    assert archive.stat().st_size == 20366995 and archive_sha == 'a968fc9648b03936ba4d61f5f9032545aa3eb958ce1a94144e5306b02394064d'
    with zipfile.ZipFile(archive) as z:
        assert z.testzip() is None and len(z.infolist()) == 149
        outer_checks = check_manifest(z.read('BACKUP-MANIFEST.sha256').decode('utf-8-sig'), z.read)
        assert len(outer_checks) == 148
        prefix = 'cnu-j-grandstand-historical/'
        package_names = [n for n in z.namelist() if n.startswith(prefix)]
        assert len(package_names) == 145
        for entry in provenance['files']:
            assert sha(z.read(prefix + entry['path'])) == entry['sha256'], entry['path']
        candidate_record = json.loads(z.read('candidate-record.json'))
        excluded_types = [n for n in z.namelist() if n.lower().endswith(('.gcode', '.html', '.jpg', '.jpeg')) or '/.git/' in n]
        assert not excluded_types, excluded_types
    official_path = Path(receipt['official_download_verification'])
    official = json.loads(official_path.read_text(encoding='utf-8-sig'))
    assert sha(official_path.read_bytes()) == receipt['official_download_verification_sha256']
    assert official['archive_sha256'] == archive_sha and official['version'] == 1
    assert official['library_file_id'] == 'libfile_03684283aedc8191900c89f2971270aa'
    # Check the already materialized official-download archive if present, not a new download.
    official_archives = list((task / 'library-support-official-download').glob('*.zip'))
    matching_official = [{'path': str(q), 'bytes': q.stat().st_size, 'sha256': sha(q.read_bytes())} for q in official_archives]
    assert any(q['sha256'] == archive_sha for q in matching_official)
    save('package-and-archive.json', {
        'checked_at_utc': datetime.datetime.now(datetime.timezone.utc).isoformat(),
        'package_files': 145, 'package_manifest_entries_verified': len(package_checks),
        'package_manifest_sha256': sha((PACKAGE / 'MANIFEST.sha256').read_bytes()),
        'local_archive': str(archive), 'archive_bytes': archive.stat().st_size, 'archive_sha256': archive_sha,
        'archive_CRC_pass': True, 'archive_entries': 149, 'outer_manifest_entries_verified': len(outer_checks),
        'all_145_archive_package_files_match_fixed_git_blobs': True,
        'outer_manifest_checks': outer_checks, 'package_manifest_checks': package_checks,
        'archive_candidate_record': candidate_record, 'disallowed_raw_file_types_found': excluded_types,
        'previously_materialized_official_archives': matching_official,
        'author_official_download_receipt_sha256': sha(official_path.read_bytes()),
        'library_identity_and_version_in_author_receipt': {'library_file_id': official['library_file_id'], 'version': official['version']},
        'new_Library_download_or_native_identity_query_performed': False,
        'scope': 'Independently verified local staged and already-materialized official ZIP bytes/CRC/manifests/Git-bound payload. Library/native metadata is the retained author receipt, not a new server/NTFS query.'
    })
    save('tool-attempts.json', {'attempts': [{
        'action': 'Read private diagnostic inventory and archive central directory',
        'result': 'CreateProcess rejected: exec-server transport disconnected; command did not start',
        'resolution': 'Subsequent small read-only exec_command with login=false succeeded. File readability had been established before failure and again after recovery.',
        'candidate_or_threshold_changes': False
    }]})
    print(json.dumps({'fixed_commit': provenance['fixed_commit'], 'fixed_unchanged_files': len(unchanged_rows),
                      'profile': sha(reviewed_profile.read_bytes()), 'gcode_only_first_time_line_differs': True,
                      'canonical_gcode_sha256': canonical_sha, 'package_files': 145,
                      'archive_sha256': archive_sha, 'all_local_archive_and_manifest_checks_pass': True}, ensure_ascii=False))


if __name__ == '__main__':
    main()
